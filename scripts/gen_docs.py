"""Generate the docs pages that must never drift from the code.

    python scripts/gen_docs.py            # (re)write the generated pages
    python scripts/gen_docs.py --check    # exit 1 if any generated page is stale (used by tests/CI)

Pages:
  docs/reference/config.md        every TrainConfig field: type, default, comment (parsed from trainer.py)
  docs/environments/prompts.md    the exact PointMaze prompts the policy sees, for both prompt styles
"""
from __future__ import annotations

import argparse
import dataclasses
import os
import re
import sys
import typing

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)

HEADER = "<!-- GENERATED by scripts/gen_docs.py -- do not edit by hand; run `make docs-gen` -->\n\n"


def _type_name(t) -> str:
    s = getattr(t, "__name__", None) if not typing.get_args(t) else None
    if s:
        return s
    args = [a for a in typing.get_args(t) if a is not type(None)]
    base = " | ".join(_type_name(a) for a in args)
    return base + (" | None" if type(None) in typing.get_args(t) else "")


def config_reference() -> str:
    from vlmrl.trainer import TrainConfig
    src = open(os.path.join(ROOT, "vlmrl/trainer.py")).read()
    body = src[src.index("class TrainConfig"):src.index("\n\n\n", src.index("class TrainConfig"))]
    comments, sections, section = {}, {}, "general"
    for line in body.splitlines()[1:]:
        m = re.match(r"\s+# (.+)$", line)
        if m:
            section = m.group(1).strip()
            continue
        m = re.match(r"\s+(\w+):[^=]+=[^#]*(?:#\s*(.*))?$", line)
        if m:
            comments[m.group(1)] = (m.group(2) or "").strip()
            sections[m.group(1)] = section
    hints = typing.get_type_hints(TrainConfig)
    from vlmrl.config import compose
    composed = compose()  # what `python scripts/train.py` actually runs with (Hydra defaults applied)
    out = [HEADER, "# Configuration reference\n\n",
           "Every field of `vlmrl.trainer.TrainConfig`, the Hydra schema. Set any of them on the command "
           "line (`python scripts/train.py field=value`) or in a YAML group file. See "
           "[Configuration](../training/configuration.md) for how the groups compose.\n\n"
           "*default* is the value after the default Hydra groups are applied (`policy=qwen3vl4b_lora "
           "task=pointmaze rollout=hf`), i.e. what `python scripts/train.py` runs with.\n"]
    current = None
    for f in dataclasses.fields(TrainConfig):
        sec = sections.get(f.name, "general")
        if sec != current:
            current = sec
            out.append(f"\n## {sec}\n\n| field | type | default | notes |\n|---|---|---|---|\n")
        default = getattr(composed, f.name)
        d = "`null`" if default is None else f"`{default!r}`".replace("|", "\\|")
        note = comments.get(f.name, "").replace("|", "\\|")
        typ = _type_name(hints[f.name]).replace("|", "\\|")
        out.append(f"| `{f.name}` | `{typ}` | {d} | {note} |\n")
    return "".join(out)


def prompts_page() -> str:
    import numpy as np
    from vlmrl.envs.pointmaze import PointMazeTextInterface, get_maze_map
    from vlmrl.types import Obs

    mm = get_maze_map("umaze")
    start = {"qpos": np.array([1.12, -0.95]), "qvel": np.zeros(2), "goal": np.array([-1.08, 1.03])}
    obs = Obs(image=np.zeros((8, 8, 3), np.uint8), state=np.array([1.12, -0.95, 0.0, 0.0]),
              extras={"goal": start["goal"]})

    def render(msg):
        return "\n".join(c["text"] if c["type"] == "text" else "<image>" for c in msg)

    out = [HEADER, "# Prompts\n\n",
           "These are the **exact** strings the policy sees on PointMaze UMaze (start (1.12, −0.95), goal "
           "(−1.08, 1.03)), rendered from `PointMazeTextInterface`. `<image>` marks where the top-down "
           "frame goes. The protocol template itself lives in `vlmrl/envs/protocol.py`; see "
           "[The robot-use protocol](../pear/protocol.md) for what each section means.\n\n"
           "Select the style with `env_kwargs.prompt_style=pear|simple`; `env_kwargs.include_state=false` "
           "drops the state JSON and goal coordinates (image-only control).\n"]
    for style, title, note in [
        ("pear", "PEAR protocol (default)", "Paper Appendix H, verbatim. Only `## ENVIRONMENT` and "
         "`## TASK` are PointMaze-specific. The action is the *change* of each quantity."),
        ("simple", "Simple (legacy)", "A shorter custom prompt with `<action>{\"dx\",\"dy\"}</action>` "
         "and velocity in the observation. Used by the first verified UMaze run."),
    ]:
        itf = PointMazeTextInterface(mm, prompt_style=style)
        out.append(f"\n## {title}\n\n{note}\n\n")
        out.append("### System prompt\n\n````text\n" + itf.system_prompt(start) + "\n````\n\n")
        out.append("### First user message\n\n````text\n" + render(itf.observation_message(obs, 0, None, False)) + "\n````\n\n")
        out.append("### After an unparseable reply (`on_invalid=noop` only)\n\n````text\n"
                   + render(itf.observation_message(obs, 1, None, True)) + "\n````\n\n")
        out.append("### A valid assistant reply\n\n````text\nThe goal is up and to the left; the wall row "
                   "blocks going straight up, so I first move left along the bottom corridor.\n"
                   + itf.format_action(np.array([-1.0, 0.0])) + "\n````\n")
    out.append("\n## Without state (`include_state=false`)\n\n````text\n"
               + render(PointMazeTextInterface(mm, include_state=False).observation_message(obs, 0, None, False))
               + "\n````\n\nThe TASK line then omits the goal coordinates: *"
               + PointMazeTextInterface(mm, include_state=False).instruction(start) + "*\n")
    return "".join(out)


PAGES = {"docs/reference/config.md": config_reference, "docs/environments/prompts.md": prompts_page}


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args()
    stale = []
    for rel, fn in PAGES.items():
        path = os.path.join(ROOT, rel)
        new = fn()
        old = open(path).read() if os.path.exists(path) else None
        if old != new:
            stale.append(rel)
            if not a.check:
                os.makedirs(os.path.dirname(path), exist_ok=True)
                with open(path, "w") as f:
                    f.write(new)
    if a.check and stale:
        print("stale generated docs (run `make docs-gen`):", *stale, sep="\n  ")
        sys.exit(1)
    print("up to date" if not stale else "wrote:\n  " + "\n  ".join(stale))


if __name__ == "__main__":
    main()
